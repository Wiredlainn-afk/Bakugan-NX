#!/usr/bin/env python3
"""Writes out/census/bakugan_d3d_census.cpp: a counting hook on every generated function in the Direct3D library's
address ranges (diagnostic only). Each hook counts calls and keeps the first arguments seen; a thread writes
census.txt next to the executable every 10 s (calls, r3..r7, lr of the first call, and the calls in the last window).
Configure the PC build with -DBAKUGAN_EXTRA_SOURCES=<abs path of the .cpp> and read census.txt.

  python3 -I tools/d3d_census_build.py [--range 0x8263D000:0x82677000 ...]
"""
import argparse, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ap = argparse.ArgumentParser()
ap.add_argument('--range', action='append', default=['0x8263D000:0x82677000', '0x82826000:0x82828000'])
a = ap.parse_args()
st = sorted(int(k, 16) for k in json.load(open(os.path.join(ROOT, 'app/generated/default/codegen.partition.json')))['assignments'])
rs = [tuple(int(x, 0) for x in r.split(':')) for r in a.range]
addrs = [s for s in st if any(lo <= s < hi for lo, hi in rs)]
out = os.path.join(ROOT, 'out', 'census')
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, 'bakugan_d3d_census.cpp'), 'w', newline='\n') as f:
    f.write('// Generated by tools/d3d_census_build.py (diagnostic only): %d counting hooks.\n' % len(addrs))
    f.write('#include <atomic>\n#include <chrono>\n#include <cstdio>\n#include <filesystem>\n#include <thread>\n\n'
            '#include <rex/filesystem.h>\n#include <rex/hook.h>\n#include <rex/ppc.h>\n\n')
    f.write('namespace {\nconstexpr uint32_t kAddr[%d] = {%s};\n' % (len(addrs), ','.join('0x%08X' % x for x in addrs)))
    f.write('''struct Entry { std::atomic<uint32_t> calls{0}; uint32_t r3 = 0, r4 = 0, r5 = 0, r6 = 0, r7 = 0, lr = 0; uint32_t last = 0; };
Entry g_entries[%d];
std::atomic<bool> g_started{false};
void Report() {
  const auto path = rex::filesystem::GetExecutableFolder() / "census.txt";
  for (;;) {
    std::this_thread::sleep_for(std::chrono::seconds(10));
    if (std::FILE* f = std::fopen(path.string().c_str(), "w")) {
      for (size_t i = 0; i < %d; ++i) {
        Entry& e = g_entries[i];
        const uint32_t c = e.calls.load(std::memory_order_relaxed);
        if (!c) continue;
        std::fprintf(f, "%%08X calls=%%u window=%%u r3=%%08X r4=%%08X r5=%%08X r6=%%08X r7=%%08X lr=%%08X\\n", kAddr[i], c,
                     c - e.last, e.r3, e.r4, e.r5, e.r6, e.r7, e.lr);
        e.last = c;
      }
      std::fclose(f);
    }
  }
}
inline void Note(size_t i, PPCContext& ctx) {
  if (!g_started.exchange(true)) std::thread(Report).detach();
  Entry& e = g_entries[i];
  if (e.calls.fetch_add(1, std::memory_order_relaxed) == 0) {
    e.r3 = ctx.r3.u32; e.r4 = ctx.r4.u32; e.r5 = ctx.r5.u32; e.r6 = ctx.r6.u32; e.r7 = ctx.r7.u32; e.lr = uint32_t(ctx.lr);
  }
}
}  // namespace
''' % (len(addrs), len(addrs)))
    for i, x in enumerate(addrs):
        f.write('extern "C" REX_FUNC(__imp__sub_%08X);\nREX_HOOK_RAW(sub_%08X) { Note(%d, ctx); __imp__sub_%08X(ctx, base); }\n' % (x, x, i, x))
print(len(addrs), 'hooks ->', os.path.join(out, 'bakugan_d3d_census.cpp'))
